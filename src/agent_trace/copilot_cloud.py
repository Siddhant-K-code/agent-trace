"""Repository hook template for GitHub Copilot cloud agent.

Copilot cloud agent loads command hooks from ``.github/hooks/*.json`` on the
repository's default branch and runs their ``bash`` entries inside an
ephemeral Linux sandbox that is discarded when the job ends. A trace written
only to that sandbox is lost, so the generated script records each hook event
with ``agent-strace hook --provider copilot`` and, when the
``AGENT_STRACE_ENDPOINT`` Agents secret is set, streams each event to an
``agent-strace server`` collector as it is recorded.

``agent-strace setup --cli copilot-cloud`` writes the two repository files
and prints a ``copilot-setup-steps.yml`` job that preinstalls agent-strace
for sessions that run on GitHub Actions.
"""

from __future__ import annotations

import json
from pathlib import Path

from . import __version__

HOOKS_RELATIVE_PATH = Path(".github") / "hooks" / "agent-strace.json"
SCRIPT_RELATIVE_PATH = Path(".github") / "hooks" / "agent-strace-cloud.sh"
SETUP_STEPS_RELATIVE_PATH = Path(".github") / "workflows" / "copilot-setup-steps.yml"
INSTALL_DIR = "/tmp/agent-strace-pkg"
TRACE_DIR = "/tmp/agent-strace-traces"

# Hook events registered for the cloud agent, in the order Copilot documents
# them, with the agent-strace hook event each one maps to. The first two can be
# the first hook of a job, so they get time for a one-time install.
CLOUD_HOOK_EVENTS = (
    ("sessionStart", "session-start", 120),
    ("userPromptSubmitted", "user-prompt", 120),
    ("preToolUse", "pre-tool", 15),
    ("postToolUse", "post-tool", 15),
    ("postToolUseFailure", "post-tool-failure", 15),
    ("agentStop", "stop", 15),
    ("subagentStart", "subagent-start", 15),
    ("subagentStop", "subagent-stop", 15),
    ("sessionEnd", "session-end", 30),
)


def find_repo_root(start: Path) -> Path:
    """Return the nearest directory at or above ``start`` that has ``.git``."""
    start = start.resolve()
    for candidate in (start, *start.parents):
        if (candidate / ".git").exists():
            return candidate
    return start


def hooks_config(redact_env: dict[str, str] | None = None) -> dict:
    """Return the ``.github/hooks/agent-strace.json`` document."""
    hooks: dict[str, list[dict]] = {}
    for copilot_event, hook_event, timeout in CLOUD_HOOK_EVENTS:
        entry: dict = {
            "type": "command",
            "bash": f"bash {SCRIPT_RELATIVE_PATH.as_posix()} {hook_event}",
            "cwd": ".",
            "timeoutSec": timeout,
        }
        if redact_env:
            entry["env"] = dict(redact_env)
        hooks[copilot_event] = [entry]
    return {"version": 1, "hooks": hooks}


def hook_script(version: str = __version__) -> str:
    """Return the bash script the repository hooks run."""
    return f"""#!/usr/bin/env bash
# Generated by agent-strace setup --cli copilot-cloud (agent-strace {version}).
# Copilot cloud agent runs this from .github/hooks/agent-strace.json with the
# hook payload on stdin. It always exits 0, so a capture problem never blocks
# or denies an agent action.
#
# The sandbox filesystem is discarded when the job ends. Set the
# AGENT_STRACE_ENDPOINT Agents secret (and AGENT_STRACE_AUTH_KEY when the
# collector requires a key) to stream each event to agent-strace server as it
# is recorded. Without an endpoint, events stay in the sandbox and are lost.
set -u

event="${{1:-}}"
version="{version}"
install_dir="${{AGENT_STRACE_INSTALL_DIR:-{INSTALL_DIR}}}"
export AGENT_TRACE_DIR="${{AGENT_TRACE_DIR:-{TRACE_DIR}}}"

have_agent_strace() {{
  command -v agent-strace >/dev/null 2>&1 || [ -f "$install_dir/agent_trace/cli.py" ]
}}

# One install attempt per job: the lock directory stops a failed or slow
# install from repeating on every later hook.
if ! have_agent_strace && [ "${{AGENT_STRACE_INSTALL:-1}}" != "0" ] \\
  && mkdir -p "$(dirname "$install_dir")" 2>/dev/null \\
  && mkdir "$install_dir.lock" 2>/dev/null; then
  python3 -m pip install --quiet --disable-pip-version-check \\
    --target "$install_dir" "agent-strace==$version" </dev/null >/dev/null 2>&1 \\
    || echo "agent-strace: install of agent-strace==$version failed; this job is not traced" >&2
fi

if [ "$event" = "session-start" ] && [ -z "${{AGENT_STRACE_ENDPOINT:-}}" ]; then
  echo "agent-strace: AGENT_STRACE_ENDPOINT is not set; events stay in the sandbox and are lost when the job ends" >&2
fi

if command -v agent-strace >/dev/null 2>&1; then
  agent-strace hook --provider copilot "$event" || true
elif [ -f "$install_dir/agent_trace/cli.py" ]; then
  # agent_trace.entry runs hooks without loading the full CLI; older releases lack it.
  module=agent_trace.cli
  [ -f "$install_dir/agent_trace/entry.py" ] && module=agent_trace.entry
  PYTHONPATH="$install_dir${{PYTHONPATH:+:$PYTHONPATH}}" \\
    python3 -m "$module" hook --provider copilot "$event" || true
else
  cat >/dev/null
fi
exit 0
"""


def setup_steps_workflow(version: str = __version__) -> str:
    """Return a ``copilot-setup-steps.yml`` that preinstalls agent-strace."""
    return f"""name: "Copilot Setup Steps"

# Runs only for Copilot sessions on GitHub Actions; cloud sandbox sessions skip
# setup steps, and the hook script installs agent-strace itself there.
on:
  workflow_dispatch:
  push:
    paths:
      - .github/workflows/copilot-setup-steps.yml
  pull_request:
    paths:
      - .github/workflows/copilot-setup-steps.yml

jobs:
  copilot-setup-steps:
    runs-on: ubuntu-latest
    permissions:
      contents: read
    steps:
      - name: Install agent-strace for the repository hooks
        run: python3 -m pip install --quiet --target {INSTALL_DIR} "agent-strace=={version}"
"""


def write_repository_files(repo_root: Path, redact_env: dict[str, str] | None = None) -> tuple[Path, Path]:
    """Write the hooks file and script under ``repo_root``; return their paths."""
    hooks_path = repo_root / HOOKS_RELATIVE_PATH
    script_path = repo_root / SCRIPT_RELATIVE_PATH
    hooks_path.parent.mkdir(parents=True, exist_ok=True)
    hooks_path.write_text(json.dumps(hooks_config(redact_env), indent=2) + "\n", encoding="utf-8")
    script_path.write_text(hook_script(), encoding="utf-8")
    script_path.chmod(0o755)
    return hooks_path, script_path
